import os
import numpy as np
from tensorflow.keras.preprocessing.image import ImageDataGenerator
from tensorflow.keras.applications import MobileNetV2
from tensorflow.keras import layers, models, optimizers
from tensorflow.keras.callbacks import EarlyStopping
from sklearn.utils.class_weight import compute_class_weight
from sklearn.metrics import confusion_matrix, classification_report

IM = (224, 224)
BATCH = 32
TRAIN_DIR = os.path.join(path, 'train_set')
TEST_DIR = os.path.join(path, 'test_set')

# Treino: aumentação moderada, incluindo variação de brilho e cor (imita a câmera)
gen_treino = ImageDataGenerator(
    rescale=1./255,
    rotation_range=30,
    width_shift_range=0.2,
    height_shift_range=0.2,
    shear_range=0.2,
    zoom_range=0.2,
    horizontal_flip=True,
    brightness_range=(0.7, 1.3),
    channel_shift_range=20.0,
    fill_mode='nearest',
    validation_split=0.2,
)

# Validação e teste: sem aumentação, só escala
gen_sem_aug = ImageDataGenerator(rescale=1./255, validation_split=0.2)

train_gen = gen_treino.flow_from_directory(
    TRAIN_DIR, target_size=IM, batch_size=BATCH,
    class_mode='binary', subset='training', shuffle=True)

val_gen = gen_sem_aug.flow_from_directory(
    TRAIN_DIR, target_size=IM, batch_size=BATCH,
    class_mode='binary', subset='validation', shuffle=True)

print("Mapeamento de classes:", train_gen.class_indices)  # esperado: rose=0, tulip=1

# Compensa o desbalanceamento entre rosas e tulipas
pesos = compute_class_weight('balanced', classes=np.unique(train_gen.classes), y=train_gen.classes)
class_weight = dict(enumerate(pesos))
print("Pesos por classe:", class_weight)

"""## 4. Criação da Estrutura da Rede Neural (CNN)"""

base = MobileNetV2(weights='imagenet', include_top=False, input_shape=(224, 224, 3))
base.trainable = False  # etapa 1: a base fica congelada

modelo = models.Sequential([
    base,
    layers.GlobalAveragePooling2D(),
    layers.Dense(256, activation='relu'),
    layers.Dropout(0.4),
    layers.Dense(128, activation='relu'),
    layers.Dropout(0.4),
    layers.Dense(64, activation='relu'),
    layers.Dense(1, activation='sigmoid'),
])

modelo.compile(
    optimizer=optimizers.Adam(learning_rate=1e-3),
    loss='binary_crossentropy',
    metrics=['accuracy'],
)
modelo.summary()

historico_1 = modelo.fit(
    train_gen,
    validation_data=val_gen,
    epochs=15,
    class_weight=class_weight,
    callbacks=[EarlyStopping(monitor='val_loss', patience=4, restore_best_weights=True, verbose=1)],
)

"""## 5. Treinamento da Rede Neural"""

# Libera só as últimas camadas da base
base.trainable = True
for layer in base.layers[:100]:
    layer.trainable = False

# BatchNormalization continua congelada: com lotes pequenos ela desestabiliza o ajuste
for layer in base.layers:
    if isinstance(layer, layers.BatchNormalization):
        layer.trainable = False

# Recompilar é obrigatório depois de mudar o trainable
modelo.compile(
    optimizer=optimizers.Adam(learning_rate=1e-5),
    loss='binary_crossentropy',
    metrics=['accuracy'],
)

historico_2 = modelo.fit(
    train_gen,
    validation_data=val_gen,
    epochs=20,
    class_weight=class_weight,
    callbacks=[EarlyStopping(monitor='val_loss', patience=5, restore_best_weights=True, verbose=1)],
)

"""## 6. Salvando e Carregando o Modelo Treinado"""

# Gerador de validação sem embaralhar, para alinhar rótulos e predições
val_fixo = gen_sem_aug.flow_from_directory(
    TRAIN_DIR, target_size=IM, batch_size=BATCH,
    class_mode='binary', subset='validation', shuffle=False)

probs_val = modelo.predict(val_fixo, verbose=0).ravel()
y_val = val_fixo.classes

# Testa limiares e escolhe o que maximiza a média entre o recall de rosa e o de tulipa
melhor = (0.5, -1)
for limiar in np.arange(0.3, 0.71, 0.01):
    pred = (probs_val >= limiar).astype(int)
    rec_rosa = ((pred == 0) & (y_val == 0)).sum() / max((y_val == 0).sum(), 1)
    rec_tulipa = ((pred == 1) & (y_val == 1)).sum() / max((y_val == 1).sum(), 1)
    score = (rec_rosa + rec_tulipa) / 2
    if score > melhor[1]:
        melhor = (round(float(limiar), 2), score)

LIMIAR = melhor[0]
print(f"Limiar escolhido na validação: {LIMIAR} (equilíbrio médio: {melhor[1]*100:.1f}%)")

"""7 - Dupla visualização do Carregamento
Menor que 0.5 = Rosas
Maior que 0.5 = Tulipas
"""

test_gen = ImageDataGenerator(rescale=1./255).flow_from_directory(
    TEST_DIR, target_size=IM, batch_size=BATCH,
    class_mode='binary', shuffle=False)

probs = modelo.predict(test_gen, verbose=0).ravel()
y_true = test_gen.classes

for nome, limiar in [("0.5 (padrão)", 0.5), (f"{LIMIAR} (validação)", LIMIAR)]:
    y_pred = (probs >= limiar).astype(int)
    print(f"\n=== Limiar {nome} ===")
    print(f"Acurácia: {(y_pred == y_true).mean()*100:.2f}%")
    print(confusion_matrix(y_true, y_pred))
    print(classification_report(y_true, y_pred, target_names=['rosa', 'tulipa']))

