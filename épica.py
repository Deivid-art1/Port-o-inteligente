from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import StratifiedKFold, cross_val_score, cross_val_predict
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import confusion_matrix, classification_report

cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)
clf = make_pipeline(StandardScaler(),
                    LogisticRegression(C=1.0, max_iter=2000, class_weight='balanced'))

scores = cross_val_score(clf, X, y, cv=cv, scoring='accuracy')
print("Acurácia por parte:", np.round(scores * 100, 2))
print(f"Média: {scores.mean()*100:.2f}% ± {scores.std()*100:.2f}")

# Previsão de cada imagem feita por um modelo que não a viu no treino
pred = cross_val_predict(clf, X, y, cv=cv)
print(confusion_matrix(y, pred))
print(classification_report(y, pred, target_names=['rosa', 'tulipa']))

